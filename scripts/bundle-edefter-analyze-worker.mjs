/**
 * Bundles eDefterAnalyze.worker into a classic (zero bare/@ import) IIFE.
 *
 * Why this exists:
 * Turbopack media-copies `src/workers/eDefterAnalyze.worker.js` into
 * `.next/static/media/` without resolving `@/` imports → WORKER_ONERROR and a
 * permanent main-thread fallback. The controlled runtime asset is therefore
 * `public/workers/eDefterAnalyze.worker.js` (same-origin classic Worker).
 *
 * Run: node ./scripts/bundle-edefter-analyze-worker.mjs
 * Production build runs this before `next build` (see run-production-build.mjs).
 */
import * as esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "public", "workers");
const targets = [
  {
    name: "eDefterAnalyze",
    entry: path.join(root, "src", "workers", "eDefterAnalyze.worker.js"),
    outfile: path.join(outDir, "eDefterAnalyze.worker.js"),
  },
  {
    name: "excelSheet",
    entry: path.join(root, "src", "workers", "excelSheet.worker.js"),
    outfile: path.join(outDir, "excelSheet.worker.js"),
  },
];

const aliasPlugin = {
  name: "annvero-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, (args) => {
      const bare = path.join(root, args.path.slice(2));
      const candidates = [
        bare,
        `${bare}.js`,
        `${bare}.jsx`,
        `${bare}.ts`,
        `${bare}.tsx`,
        path.join(bare, "index.js"),
      ];
      for (const candidate of candidates) {
        if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) {
          return { path: candidate };
        }
      }
      return { path: `${bare}.js` };
    });
  },
};

function assertBundleSafe(source) {
  const checks = [
    [/from\s+["']@\//, "@/ import"],
    [/import\s*\(\s*["']@\//, "@/ dynamic import"],
    [/sourceMappingURL/i, "sourceMappingURL"],
    [/process\.env/i, "process.env"],
    [/\b(?:fetch|XMLHttpRequest|importScripts|WebSocket)\b/, "network-capable runtime API"],
    [/sk_live|sk_test|SUPABASE_SERVICE|BEGIN PRIVATE KEY/i, "secret-like token"],
  ];
  for (const [re, label] of checks) {
    if (re.test(source)) {
      throw new Error(`Bundle safety failed: ${label}`);
    }
  }
  if (!/onmessage/.test(source)) {
    throw new Error("Bundle missing onmessage handler");
  }
}

fs.mkdirSync(outDir, { recursive: true });

const outputs = [];
for (const target of targets) {
  await esbuild.build({
    absWorkingDir: root,
    entryPoints: [target.entry],
    outfile: target.outfile,
    bundle: true,
    format: "iife",
    platform: "browser",
    target: ["es2020"],
    logLevel: "warning",
    splitting: false,
    sourcemap: false,
    minify: false,
    treeShaking: true,
    legalComments: "none",
    keepNames: false,
    alias: {
      "node:crypto": path.join(root, "scripts", "shims", "node-crypto-browser.js"),
      crypto: path.join(root, "scripts", "shims", "node-crypto-browser.js"),
    },
    plugins: [aliasPlugin],
    banner: {
      js: `/* annvero ${target.name} classic worker — generated by scripts/bundle-edefter-analyze-worker.mjs; do not edit */`,
    },
  });
  const source = fs.readFileSync(target.outfile, "utf8");
  assertBundleSafe(source);
  outputs.push({
    name: target.name,
    entry: path.relative(root, target.entry).replaceAll("\\", "/"),
    outfile: path.relative(root, target.outfile).replaceAll("\\", "/"),
    bytes: Buffer.byteLength(source),
    sha256: createHash("sha256").update(source).digest("hex"),
  });
}

console.log(
  JSON.stringify(
    {
      ok: true,
      outputs,
      note: "Canonical classic worker assets",
    },
    null,
    2
  )
);
